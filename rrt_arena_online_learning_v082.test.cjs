'use strict';
const test=require('node:test'),assert=require('node:assert/strict'),fs=require('node:fs');
const L=require('./rrt_arena_online_learning_v082.js');
const validStyles=new Set(['balanced','aggressive','cautious']);
test('Online learner starts with the existing balanced tactic; no power/stat changes',()=>{
 const a=L.create();
 assert.equal(a.style,'balanced');
 assert.equal(a.enabled,true);
 assert.equal(L.tick(a,{visible:false,underFire:false},0).style,'balanced');
 assert.deepEqual(L.STYLES,['balanced','aggressive','cautious']);
 assert.ok(!('hp' in a)&&!('aim' in a)&&!('baseFire' in a));
});
test("learning preserves the player\'s chosen baseline style before enough feedback exists",()=>{
 const a=L.create(true,'cautious');
 assert.equal(a.style,'cautious');
 assert.equal(L.tick(a,{visible:true},0).style,'cautious');
 L.tick(a,{visible:true},3.1);
 assert.equal(a.style,'cautious','no outcome means do not invent a better strategy');
 const b=L.create(true,'aggressive');
 L.tick(b,{visible:true},0);
 assert.equal(b.style,'aggressive');
});
test('learns only from owner shots, personally confirmed hits, and damage personally received',()=>{
 const a=L.create();
 L.tick(a,{visible:true,underFire:false},0);
 L.recordShot(a);
 assert.equal(L.recordConfirmedHit(a,11,false),false,'unseen hit must not grant learning reward');
 assert.equal(L.recordConfirmedHit(a,11,true),true);
 L.recordDamage(a,5);
 L.tick(a,{visible:true,underFire:false},3.2);
 const status=L.summary(a);
 assert.equal(status.updates,1);
 assert.equal(status.shots,1);
 assert.equal(status.confirmedHits,1);
 assert.equal(status.confirmedDamage,11);
 assert.equal(status.receivedDamage,5);
 assert.equal(status.contexts.contact.balanced.samples,1);
 assert.ok(status.contexts.contact.balanced.mean>0);
});
test('trains different strategies from outcome rewards, not a fixed decision schedule',()=>{
 const a=L.create();
 L.tick(a,{visible:true},0);
 L.recordShot(a);L.recordConfirmedHit(a,12,true);
 L.tick(a,{visible:true},3.1);
 assert.equal(a.style,'aggressive');
 L.recordShot(a);L.recordDamage(a,70);
 L.tick(a,{visible:true},6.2);
 assert.equal(a.style,'cautious');
 L.recordShot(a);L.recordConfirmedHit(a,22,true);
 L.tick(a,{visible:true},9.3);
 assert.equal(a.style,'cautious','evidence-led action wins once all three strategies tried');
 const s=L.summary(a);
 assert.equal(s.updates,3);assert.ok(s.switches>=2);
 assert.ok(s.contexts.contact.cautious.mean>s.contexts.contact.aggressive.mean);
});
test('under-fire training context is distinct from visible-contact outcome',()=>{
 const a=L.create();
 L.tick(a,{visible:true},0);
 L.recordDamage(a,15);L.tick(a,{visible:true,underFire:true},3.5);
 assert.equal(a.context,'under_fire');
 L.recordShot(a);L.recordConfirmedHit(a,12,true);
 L.tick(a,{visible:true,underFire:true},7);
 const s=L.summary(a);
 assert.equal(s.contexts.contact.balanced.samples,1);
 assert.equal(s.contexts.under_fire.balanced.samples,1);
});
test('no feedback makes no invented improvement, and disabled learning is a pure no-op',()=>{
 const a=L.create();
 L.tick(a,{visible:true},0);
 L.tick(a,{visible:true},3.5);
 assert.equal(L.summary(a).updates,0);
 const b=L.create(false);
 L.tick(b,{visible:true,underFire:true},0);
 L.recordShot(b);L.recordDamage(b,18);L.recordConfirmedHit(b,15,true);
 L.tick(b,{visible:true,underFire:true},12);
 const s=L.summary(b);
 assert.equal(s.enabled,false);assert.equal(s.updates,0);
 assert.equal(s.style,'balanced');assert.equal(s.shots,0);
});
test('individual learner states never share policy statistics',()=>{
 const a=L.create(),b=L.create();
 L.tick(a,{visible:true},0);L.tick(b,{visible:true},0);
 L.recordShot(a);L.recordConfirmedHit(a,10,true);
 L.tick(a,{visible:true},4);L.tick(b,{visible:true},4);
 assert.equal(L.summary(a).updates,1);assert.equal(L.summary(b).updates,0);
 assert.notStrictEqual(a.contexts,b.contexts);
});
test('invalid and extreme observations are bounded; completed policy supports own full-match review',()=>{
 const a=L.create();
 L.tick(a,{visible:true},0);
 L.recordShot(a);L.recordDamage(a,NaN);L.recordDamage(a,-2);
 assert.equal(L.recordConfirmedHit(a,Infinity,true),false);
 L.recordDamage(a,100000);
 L.finish(a,3.5);
 const s=L.summary(a);
 assert.equal(s.updates,1);
 assert.ok(Number.isFinite(s.meanReward));
 assert.ok(s.contexts.contact.balanced.mean>=-1);
 assert.ok(s.contexts.contact.balanced.mean<=1);
 assert.ok(validStyles.has(s.style));
});
test('deployed single-file game includes same offline learning source and opt-in UI',()=>{
 const html=fs.readFileSync(require('node:path').join(__dirname,'index.html'),'utf8');
 const m=html.match(/<script id="onlineLearningCore">\n([\s\S]*?)<\/script>/);
 assert.ok(m);
 assert.equal(m[1].trim(),fs.readFileSync(require('node:path').join(__dirname,'rrt_arena_online_learning_v082.js'),'utf8').trim());
 assert.match(html,/id="duel2OnlineLearning"/);
 assert.match(html,/onlineCore=globalThis\.RRTArenaOnlineLearning/);
 assert.match(html,/bot\.duelLearner=onlineCore\.create/);
 assert.match(html,/onlineCore\.tick\(bot\.duelLearner,/);
 assert.match(html,/function botStyle\(bot\)/);
 assert.match(html,/onlineCore\.recordDamage\(victim\.duelLearner/);
 assert.match(html,/onlineCore\.recordConfirmedHit\(shooter\.duelLearner/);
});
